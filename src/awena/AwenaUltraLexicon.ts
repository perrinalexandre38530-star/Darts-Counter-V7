function domainBoost(entry: UltraEntry, context?: AwenaRuntimeContext) {
  const sport = norm(context?.sport || "");
  const route = norm(context?.route || "");
  if (entry.domain === "darts" && (sport.includes("dart") || /x01|cricket|killer|darts/.test(route))) return 1.8;
  if (entry.domain === "petanque" && (sport.includes("petanque") || route.includes("petanque"))) return 1.8;
  if (entry.domain === "pingpong" && (sport.includes("ping") || route.includes("pingpong"))) return 1.8;
  if (entry.domain === "molkky" && (sport.includes("molk") || route.includes("molkky"))) return 1.8;
  if (entry.domain === "football" && (sport.includes("foot") || route.startsWith("foot"))) return 1.8;
  if (entry.domain === "babyfoot" && (sport.includes("baby") || route.includes("babyfoot"))) return 1.8;
  if (entry.domain === "dice" && (sport.includes("dice") || route.includes("dice"))) return 1.8;
  return 0;
}

function scoreEntry(entry: UltraEntry, question: string, rememberedTopic?: string, context?: AwenaRuntimeContext) {
  const q = norm(question);
  const qTokens = new Set(tokens(q));
  let score = domainBoost(entry, context);
  for (const raw of entry.aliases) {
    const alias = norm(raw);
    if (!alias) continue;
    if (q === alias) score += 30;
    else if (alias.length >= 4 && q.includes(alias)) score += 15;
    const aliasTokens = tokens(alias);
    let matched = 0;
    for (const token of aliasTokens) {
      if (qTokens.has(token)) { matched += 1; score += token.length >= 6 ? 3.2 : 1.8; }
    }
    if (aliasTokens.length >= 2 && matched === aliasTokens.length) score += 6.5;
  }
  const title = norm(entry.title);
  if (title && q.includes(title)) score += 10;
  if (rememberedTopic === `ultra:${entry.id}`) score += 7;
  return score;
}

export function answerAwenaUltraLexicon(question: string, context: AwenaRuntimeContext, rememberedTopic?: string): AwenaReply | null {
  const q = norm(question);
  if (!q) return null;
  let best: { entry: UltraEntry; score: number } | null = null;
  for (const entry of ENTRIES) {
    const score = scoreEntry(entry, q, rememberedTopic, context);
    if (!best || score > best.score) best = { entry, score };
  }
  if (!best || best.score < 9.5) return null;
  const reference = best.entry.source
    ? `\n\n> **Référence :** ${best.entry.source}. Pour une partie active, les paramètres réellement appliqués dans MULTISPORTS SCORING restent prioritaires.`
    : "";
  return {
    text: `${best.entry.text}${reference}`,
    modeId: context.mode || null,
    knowledgeTopic: `ultra:${best.entry.id}`,
  };
}

export function awenaUltraLexiconCount() { return ENTRIES.length; }
export function awenaUltraLexiconDomains() { return [...new Set(ENTRIES.map((entry) => entry.domain))]; }
export function awenaUltraLexiconKinds() { return [...new Set(ENTRIES.map((entry) => entry.kind))]; }
