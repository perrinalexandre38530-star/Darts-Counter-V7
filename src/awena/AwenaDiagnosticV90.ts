function rememberedId(topic?: string) { return String(topic||"").startsWith("diagv90:") ? String(topic).slice(8) : ""; }
function score(e:DiagnosticV90Entry,q:string,remembered?:string) {
  let s=rememberedId(remembered)===e.id?12:0; const qt=new Set(toks(q));
  for(const raw of [e.title,...e.aliases]){const a=norm(raw); if(q===a)s+=48; else if(a.length>=4&&q.includes(a))s+=21; const at=toks(a); let m=0; for(const t of at)if(qt.has(t)){m++;s+=t.length>=6?4:2.3} if(at.length>=2&&m===at.length)s+=9;}
  if(/marche pas|fonctionne pas|bug|erreur|bloque|bloqué|fige|figé|lent|lente|manque|absent|incoherent|incohérent|diagnostic|pourquoi/.test(q))s+=3;
  return s;
}
function full(e:DiagnosticV90Entry) {
  return `## DIAGNOSTIC · ${e.title.toUpperCase()}\nJe vais commencer par les causes les plus probables et les vérifications les moins risquées.\n\n## CAUSES PROBABLES\n${bullets(e.causes)}\n\n## À VÉRIFIER DANS CET ORDRE\n${numbered(e.checks)}\n\n## CORRECTIONS / SUITE\n${numbered(e.fixes)}${e.avoid.length?`\n\n## À ÉVITER\n${bullets(e.avoid)}`:""}\n\n> Donne-moi le résultat d’une vérification ou le message d’erreur exact : je garde ce diagnostic en mémoire.`;
}
function follow(e:DiagnosticV90Entry,q:string) {
  if(/cause|pourquoi/.test(q)) return `## CAUSES · ${e.title.toUpperCase()}\n${bullets(e.causes)}`;
  if(/commence|premier|d abord|d'abord|verif|vérif|check/.test(q)) return `## PREMIÈRES VÉRIFICATIONS · ${e.title.toUpperCase()}\n${numbered(e.checks)}`;
  if(/corrig|solution|reparer|réparer|quoi faire/.test(q)) return `## CORRECTIONS · ${e.title.toUpperCase()}\n${numbered(e.fixes)}`;
  if(/eviter|éviter|danger|risque/.test(q)) return `## À ÉVITER · ${e.title.toUpperCase()}\n${bullets(e.avoid)}`;
  return full(e);
}
export function answerAwenaDiagnosticV90(question:string, context:AwenaRuntimeContext, rememberedTopic?:string):AwenaReply|null {
  const q=norm(question); if(!q)return null;
  const rid=rememberedId(rememberedTopic);
  const shortFollow=/^(?:pourquoi|quelle cause|quelles causes|par quoi commencer|quoi verifier|quoi vérifier|quelle solution|quoi faire|et maintenant|et ensuite|ca ne marche toujours pas|ça ne marche toujours pas)$/i.test(String(question||"").trim());
  if(shortFollow&&rid){const e=ENTRIES.find(x=>x.id===rid); if(e)return {text:follow(e,q),knowledgeTopic:`diagv90:${e.id}`,modeId:context.mode||null};}
  let best:{e:DiagnosticV90Entry;s:number}|null=null; for(const e of ENTRIES){const s=score(e,q,rememberedTopic);if(!best||s>best.s)best={e,s}}
  if(!best||best.s<15)return null;
  return {text:full(best.e),knowledgeTopic:`diagv90:${best.e.id}`,modeId:context.mode||null};
}
