function norm(v: string) { return String(v||"").toLowerCase().normalize("NFD").replace(/[\u0300-\u036f]/g,"").replace(/[’']/g," ").replace(/[_/\\.-]+/g," ").replace(/[^a-z0-9+%\s]/g," ").replace(/\s+/g," ").trim(); }
function toks(v: string) { return norm(v).split(" ").filter(t=>t.length>1 && !STOP.has(t)); }
function bullets(v:string[]) { return v.map(x=>`- ${x}`).join("\n"); }
