function scoreEntry(entry: SourceEntry, q: string, context: AwenaRuntimeContext) {
  let score = 0; const route = norm(context.route || ""); const sport = norm(context.sport || "");
  const er = norm(entry.route); const ec = norm(entry.component);
  if (route && er && route === er) score += 18; else if (route && er && (route.includes(er) || er.includes(route))) score += 8;
  if (sport && norm(entry.sport).includes(sport)) score += 2;
  if (ec && q.includes(ec)) score += 14; if (er && q.includes(er)) score += 14;
  const qt = new Set(tokens(q));
  for (const fact of entry.facts) { let overlap = 0; for (const t of tokens(fact)) if (qt.has(t)) overlap += 1; if (overlap >= 2) score += Math.min(8, overlap * 2); }
  return score;
}

function selectFacts(entry: SourceEntry, q: string) {
  const qt = new Set(tokens(q));
  const ranked = entry.facts.map((fact, index) => { let overlap = 0; for (const t of tokens(fact)) if (qt.has(t)) overlap += 1; return { fact, overlap, index }; }).sort((a,b) => b.overlap - a.overlap || a.index - b.index);
  const hasMatch = ranked.some((x) => x.overlap > 0);
  return ranked.filter((x) => !hasMatch || x.overlap > 0).slice(0, hasMatch ? 10 : 12).map((x) => x.fact);
}

export function answerAwenaSourceAtlas(question: string, context: AwenaRuntimeContext): AwenaReply | null {
  const q = norm(question); if (!q) return null;
  const screenIntent = /(?:ecran|page|ici|bouton|champ|option|reglage|controle|menu|carte|onglet|visible|affiche|selection|selecteur)/.test(q);
  let best: { entry: SourceEntry; score: number } | null = null;
  for (const entry of ENTRIES) { const score = scoreEntry(entry, q, context); if (!best || score > best.score) best = { entry, score }; }
  if (!best) return null;
  const currentRouteMatch = !!context.route && norm(best.entry.route) === norm(context.route);
  if (best.score < 10 || (!screenIntent && !currentRouteMatch && best.score < 16)) return null;
  if (!screenIntent && currentRouteMatch) { const qt = new Set(tokens(q)); const overlap = best.entry.facts.some((f) => tokens(f).filter((t) => qt.has(t)).length >= 2); if (!overlap) return null; }
  const facts = selectFacts(best.entry, q); if (!facts.length) return null;
  const title = best.entry.route ? best.entry.route.replace(/_/g, " ") : best.entry.component;
  return { text: `## INFORMATIONS DE L’ÉCRAN — ${title.toUpperCase()}\n${facts.map((f) => `- ${f}`).join("\n")}\n\n> Ces éléments proviennent des libellés et aides présents dans le code actuel de cet écran. Je les utilise comme contexte, sans inventer une option absente.`, knowledgeTopic: `source:${best.entry.route || best.entry.component}`, modeId: context.mode || null };
}

