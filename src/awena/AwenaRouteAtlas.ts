function scoreRoute(question: string, entry: RouteEntry) {
  const q = norm(question);
  let score = 0;
  const candidates = [entry.id, entry.label, ...entry.aliases].map(norm).filter(Boolean);
  for (const alias of candidates) {
    if (q === alias) score = Math.max(score, 100);
    else if (alias.length >= 3 && q.includes(alias)) score = Math.max(score, 68 + Math.min(20, alias.length / 2));
  }
  const qTokens = new Set(tokens(q));
  const eTokens = new Set(tokens(candidates.join(" ")));
  let overlap = 0;
  for (const token of qTokens) if (eTokens.has(token)) overlap += 1;
  score += overlap * 10;
  return score;
}

function navigationIntent(q: string) {
  return /ou (?:est|sont)|ou trouver|ou aller|comment ouvrir|comment acceder|comment accéder|comment aller|emmene moi|amene moi|ouvre|lance|quelle page|quel ecran|quel écran|a quoi sert cette page|à quoi sert cette page/.test(norm(q));
}

export function answerAwenaRouteAtlas(question: string): AwenaReply | null {
  const q = norm(question);
  if (!q) return null;
  let best: { entry: RouteEntry; score: number } | null = null;
  for (const entry of ROUTES) {
    const score = scoreRoute(q, entry);
    if (!best || score > best.score) best = { entry, score };
  }
  if (!best || best.score < (navigationIntent(q) ? 28 : 72)) return null;

  const action: AwenaAction = {
    id: `route-atlas-${best.entry.id}`,
    label: `Ouvrir ${best.entry.label}`,
    kind: "navigate",
    route: best.entry.id,
  };

  return {
    knowledgeTopic: `route:${best.entry.id}`,
    text: `## ${best.entry.label.toUpperCase()}
${best.entry.purpose}

## OÙ LE TROUVER
Je peux ouvrir directement cet écran avec le bouton ci-dessous.

> Cet index est construit à partir des routes réellement présentes dans l'application actuelle.`,
    actions: [action],
  };
}

export function awenaRouteAtlasCount() {
  return ROUTES.length;
}
