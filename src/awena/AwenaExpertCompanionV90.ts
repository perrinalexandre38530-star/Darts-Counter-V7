function rememberedId(topic?: string) { return String(topic || "").startsWith("expertv90:") ? String(topic).slice(10) : ""; }

function score(entry: ExpertV90Entry, q: string, rememberedTopic?: string) {
  let s = rememberedId(rememberedTopic) === entry.id ? 11 : 0;
  const qt = new Set(tokens(q));
  for (const raw of [entry.title, ...entry.aliases]) {
    const a = norm(raw);
    if (!a) continue;
    if (q === a) s += 48;
    else if (a.length >= 4 && q.includes(a)) s += 20;
    const at = tokens(a);
    let m = 0;
    for (const t of at) if (qt.has(t)) { m++; s += t.length >= 6 ? 3.8 : 2.2; }
    if (at.length >= 2 && m === at.length) s += 8;
  }
  return s;
}

function render(entry: ExpertV90Entry, q: string) {
  const problem = /marche pas|fonctionne pas|erreur|probleme|problème|bloque|bloqué|bug|diagnostic|incoherent|incohérent/.test(q);
  const how = /comment|utiliser|configurer|mettre en place|faire pour|en pratique|a quoi ca sert|à quoi ça sert/.test(q);
  const deep = /detail|détail|technique|expert|precis|précis|approfond|complet|complexe|pourquoi|difference|différence|compare/.test(q);
  let out = `## ${entry.title.toUpperCase()}\n${entry.simple}`;
  if (deep || (!how && !problem && q.length > 56)) out += `\n\n## COMPRENDRE EN PROFONDEUR\n${entry.deep}`;
  if (how || deep) out += `\n\n## EN PRATIQUE\n${entry.practical}`;
  if (problem || deep) out += `\n\n## DIAGNOSTIC / PIÈGES\n${entry.diagnostic}`;
  if (!deep && !how && !problem) out += `\n\n**À retenir :** ${entry.practical}`;
  return out;
}

export function answerAwenaExpertCompanionV90(question: string, context: AwenaRuntimeContext, rememberedTopic?: string): AwenaReply | null {
  const q = norm(question);
  if (!q) return null;
  const rid = rememberedId(rememberedTopic);
  const follow = /^(?:plus de details|plus de détails|approfondis|explique davantage|pourquoi|comment|et en pratique|ca ne marche pas|ça ne marche pas|diagnostic|compare|difference|différence)$/i.test(String(question || "").trim());
  if (follow && rid) {
    const e = ENTRIES.find((x) => x.id === rid);
    if (e) return { text: render(e, `${q} detail`), knowledgeTopic: `expertv90:${e.id}`, modeId: context.mode || null };
  }
  let best: { entry: ExpertV90Entry; score: number } | null = null;
  for (const entry of ENTRIES) {
    const s = score(entry, q, rememberedTopic);
    if (!best || s > best.score) best = { entry, score: s };
  }
  if (!best || best.score < 14) return null;
  return { text: render(best.entry, q), knowledgeTopic: `expertv90:${best.entry.id}`, modeId: context.mode || null };
}

