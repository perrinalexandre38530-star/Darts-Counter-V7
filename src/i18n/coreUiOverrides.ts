export function registerCoreUiLiteralTranslations(): void {
  for (const [target, values] of Object.entries(CORE_UI_OVERRIDES)) {
    for (const [field, sourceLanguage, source] of CORE_SOURCE_FORMS) {
      const key = Object.entries(CORE_FIELD_BY_KEY).find(([, value]) => value === field)?.[0];
      if (!key) continue;
      const translated = values[key];
      if (!translated) continue;
      const rendered = source === source.toLocaleUpperCase(sourceLanguage)
        ? translated.toLocaleUpperCase(target)
        : translated;
      registerUiLiteralTranslation(source, sourceLanguage, target, rendered);
    }
  }
}

