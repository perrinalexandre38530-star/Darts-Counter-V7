export function getLocaleProfile(locale: string | null | undefined): DartsLiveLocaleProfile {
  const key = String(locale || "fr").toLowerCase();
  return DARTS_LIVE_LOCALE_PROFILES[key] || DARTS_LIVE_LOCALE_PROFILES.en;
}

export function getRecommendedSources(locale: string | null | undefined): DartsLiveSource[] {
  const profile = getLocaleProfile(locale);
  const preferred = new Set<DartsLiveRegion>(profile.preferredRegions);
  return DARTS_LIVE_SOURCES.filter((source) => source.regions.some((region) => preferred.has(region)));
}

export function getAvailableRegions(locale: string | null | undefined): DartsLiveRegion[] {
  const profile = getLocaleProfile(locale);
  const result: DartsLiveRegion[] = [];
  for (const region of [...profile.preferredRegions, ...profile.fallbackRegions, "global" as DartsLiveRegion]) {
    if (!result.includes(region)) result.push(region);
  }
  return result;
}
