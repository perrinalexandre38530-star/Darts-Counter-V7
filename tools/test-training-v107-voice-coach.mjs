import assert from 'node:assert/strict';
import fs from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const source = path.join(root, 'src/training/profile/trainingVoiceScripts.ts');
const { buildTrainingStepVoiceText, buildTrainingResultVoiceText, buildTrainingSessionVoiceText, pronounceDartSegments } = await import(`file://${source}`);
const script = buildTrainingStepVoiceText({ title: 'Doubles', engine:'target_hits', maxDarts:30 }, {objective:'Toucher D20', cue:'Reste régulier.', phaseLabel:'BLOC PRINCIPAL'}, 1,3);
assert.match(script, /Étape 2 sur 3/);
assert.match(script, /Toucher double 20/);
assert.equal(pronounceDartSegments("T20, D16, S5, DBULL"), "triple 20, double 16, simple 5, double bull");
const noAccuracy = buildTrainingResultVoiceText({title:'Sprint',success:true,performanceScore:65,completionPct:77,accuracyPct:null});
assert.match(noAccuracy, /Précision non mesurée/);
assert.doesNotMatch(noAccuracy, /Précision mesurée/);
const measured = buildTrainingResultVoiceText({title:'Double',success:false,performanceScore:34,completionPct:10,accuracyPct:23.5});
assert.match(measured, /Précision mesurée : 24 pour cent/);
assert.doesNotMatch(measured, /Précision non mesurée/);
const recap = buildTrainingSessionVoiceText({title:'Programme',successes:2,steps:3,performance:73.7,precisionUnavailable:true,accuracyPct:0,advice:'Travaille le double 16.'});
assert.match(recap,/2 étapes réussies sur 3/);
assert.match(recap,/Précision non mesurée/);
assert.match(recap,/Travaille le double 16/);
const page = fs.readFileSync(path.join(root,'src/training/modes/lab/TrainingLabPlay.tsx'),'utf8');
const hook = fs.readFileSync(path.join(root,'src/training/ui/useTrainingVoiceCoach.ts'),'utf8');
const extended = fs.readFileSync(path.join(root,'src/training/modes/lab/TrainingCustomExercisePlay.tsx'),'utf8');
assert.match(page,/voiceCoach\.say\(spokenStep\)/);
assert.match(page,/voiceCoach\.say\(spokenSummary\)/);
assert.match(page,/aria-pressed=\{voiceCoach\.automatic\}/);
assert.match(page,/onVisit=\{onVisit\}/);
assert.match(page,/onQuickVisit=\{onQuickVisit\}/);
assert.match(hook,/if \(!automatic \|\| !text/);
assert.match(hook,/!settings\.enabled \|\| !settings\.voiceEnabled/);
assert.match(hook,/awenaVoice\.speak\(/);
assert.match(hook,/awenaVoice\.onSpeechTiming/);
assert.match(hook,/const \{ muted \} = useAudio\(\)/);
assert.match(extended,/voiceCoach\.say\(spokenCustomStep\)/);
assert.match(extended,/custom:\$\{exercise\.id\}:\$\{technique \? techniqueStage : 0\}/);
assert.match(extended,/onQuickVisit=\{onQuickVisit\}/);
console.log('OK — guidage standard + technique, mute global, keypad/score et aucune précision inventée.');
