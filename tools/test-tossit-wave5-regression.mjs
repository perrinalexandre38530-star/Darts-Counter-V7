import assert from 'node:assert/strict';
import { TOSSIT_MODES, newTossitGame as fresh, applyTossitAction as play, undoTossitAction as undo, summaryForTossit } from '../src/pages/tossit/tossitEngine.ts';
const players = [{ id:'a',name:'Alice' },{ id:'b',name:'Bob' }];
for (const id of ['thief_cop','reach','rainbow']) assert(TOSSIT_MODES.some(m=>m.id===id),`${id} playable`);
assert(TOSSIT_MODES.length>=16,'Wave5 modes not lost');
let thief=fresh('thief_cop',players,6,42,4,2);
assert.equal(thief.victoryTarget,2);
assert.throws(()=>play(thief,{kind:'thief_cop',captures:['takedown','direct']}),/ends the round/);
thief=play(thief,{kind:'thief_cop',captures:['direct','handcuff','takedown']});
assert.equal(thief.scores.b,6);
assert.equal(thief.thiefCopWins.b,1);
assert.equal(undo(thief).scores.b,0);
thief=play(thief,{kind:'thief_cop',captures:['direct','direct']});
assert.equal(thief.finished,true);
assert.equal(thief.winnerId,'b');
assert.equal(summaryForTossit(thief).thiefCopTakedowns.b,1);
let reach=fresh('reach',players,3,42,4,3);
assert.throws(()=>play(reach,{kind:'reach',bestCm:3,stuck:0}),/Invalid reach/);
for(const [cm,stuck] of [[100,2],[101,1],[120,3],[115,3],[125,2],[115,2]]) reach=play(reach,{kind:'reach',bestCm:cm,stuck});
assert.equal(reach.finished,true);
assert.equal(reach.winnerId,'a');
assert.equal(undo(reach).finished,false);
let rainbow=fresh('rainbow',players,3,43,4,3);
assert.throws(()=>play(rainbow,{kind:'rainbow',pattern:'stack',colors:2,stackHeight:2,completed:true}),/Invalid creative/);
for(let i=0;i<6;i++) rainbow=play(rainbow,{kind:'rainbow',pattern:'ring',colors:i%2?3:5,stackHeight:0,completed:true});
assert.equal(rainbow.finished,true);
assert.equal(rainbow.winnerId,'a');
console.log('TOSSIT Wave5 regression OK (3 modes + undo + invalid inputs)');
