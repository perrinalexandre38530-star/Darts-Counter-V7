import assert from 'node:assert/strict';
import fs from 'node:fs';
import { CHALLENGE_ARCADE_CATALOG } from '../src/lib/challengeArcadeCatalog.ts';
import { arcadeRuleDetails } from '../src/lib/challengeArcadeEngine.ts';

const read = path => fs.readFileSync(path, 'utf8');
const catalog = read('src/training/catalog/challengeTrainingCatalog.ts');
const lab = read('src/training/modes/lab/TrainingLabConfig.tsx');
const app = read('src/App.tsx');
const config = read('src/pages/ChallengeConfig.tsx');
const play = read('src/pages/ChallengePlay.tsx');
const arcade = read('src/pages/ChallengeArcadePlay.tsx');
const cards = read('src/training/profile/trainingSessionCards.ts');
const ui = read('src/training/ui/TrainingChallengeCatalog.tsx');

assert.equal(CHALLENGE_ARCADE_CATALOG.length, 44, '44 official arcade entries');
assert.equal(new Set(CHALLENGE_ARCADE_CATALOG.map(row => row.id)).size, 44, 'unique arcade IDs');
assert.ok(CHALLENGE_ARCADE_CATALOG.every(row => row.status === 'ready'), 'V135 challenge states are playable');
assert.equal((catalog.match(/\{ id: 'challenge_/g) || []).length, 12, '12 classic Challenge training presets');
assert.match(catalog, /CHALLENGE_ARCADE_CATALOG\.map\(\(item\) =>/, 'mirror official arcade source, no stale copy');
assert.match(catalog, /status: isArcadeChallengePlayable\(item\.id\)/, 'use source of truth for ready states');
assert.match(catalog, /minPlayers: arcadeRuleDetails\(/, 'multi requirements from source of truth');
assert.match(catalog, /\.\.\.CHALLENGE_TRAINING_CATALOG, \.\.\.CHALLENGE_TRAINING_ARCADE_CATALOG/, '56 catalogue entries');
assert.match(catalog, /trainingOrigin: 'training_lab'/, 'origin explicitly marked');
const multiIds = CHALLENGE_ARCADE_CATALOG.filter(item => arcadeRuleDetails({catalogChallengeId:item.id,catalogLine:20,catalogRounds:5,catalogVariant:'classic'}).minPlayers > 1);
assert.equal(multiIds.length, 5, '5 official modes require at least 2 players; ghost mode remains solo');
assert.match(lab, /exercisePanel === "challenge" && <TrainingChallengeCatalog/, 'tab visible');
assert.match(lab, /\(preset\.minPlayers \|\| 1\) > 1/, 'multi sessions open configurator');
assert.match(lab, /loadTrainingArcadeDraft/, 'arcade draft resume');
assert.match(app, /challengeCatalog/, 'open Challenge catalog after return');
assert.match(app, /onOpenChallenge=\{\(config, presetId, snapshot\)/, 'route typed into ChallengePlay');
assert.match(app, /onCustomizeChallenge=\{\(presetId, participantId\)/, 'configurator handoff');
assert.match(config, /fromTrainingLab &&?/, 'ChallengeConfig receives training route');
assert.match(config, /CHALLENGE_TRAINING_ARCADE_CATALOG\.find\(row => row\.arcadeId === catalogChallengeId\)/, 'customized arcade modes retain the correct catalog identity');
assert.match(config, /!fromTrainingLab\)writeChallengePreset/, 'no overwrite of competitive preset draft');
assert.match(play, /if\(historyStatsOnly\|\|fromTrainingLab\|\|log\.length===0\) return;/, 'no standard History writes in training');
assert.match(play, /if\(historyStatsOnly\|\|fromTrainingLab\|\|!done\|\|onlineSubmittedRef/, 'no online submit in training');
assert.match(play, /saveTrainingChallengeDraft/, 'classic draft persists');
assert.match(play, /recordTrainingDetailedSession/, 'classic results persist privately');
assert.match(arcade, /if\(isHistoryView\|\|fromTrainingLab\|\|!ready\|\|!hits\.length\)return;/, 'no arcade History writes in training');
assert.match(arcade, /if\(!fromTrainingLab&&pendingSaveRef\.current\.dirty/, 'no arcade unmount History flush');
assert.match(arcade, /recordTrainingDetailedSession/, 'arcade results persist privately');
assert.match(arcade, /saveTrainingArcadeDraft/, 'arcade draft saves');
assert.match(cards, /const challengeCards: TrainingSessionCard\[\]/, 'training challenge cards');
assert.match(cards, /row\.config\?\.trainingOrigin === "training_lab"/, 'training cards exclude competitive rounds');
assert.match(ui, /\(preset\.minPlayers \|\| 1\) > 1 \? 'CHOISIR JOUEURS'/, 'no invalid multiplayer solo start');
assert.doesNotMatch(ui, /les 42 autres présentent leurs règles/, 'outdated preview copy removed');
console.log('✅ TRAINING CHALLENGE V135 REBASE: 56 linked sheets, 44 official ready modes, 5 multi prerequisites, routing, drafts, private results and History/ONLINE guards.');
