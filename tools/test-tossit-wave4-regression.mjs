import assert from 'node:assert/strict';
import { TOSSIT_MODES, TOSSIT_PLANNED, newTossitGame, applyTossitAction as move, undoTossitAction as undo, summaryForTossit } from '../src/pages/tossit/tossitEngine.ts';
const players = [{ id: 'a', name: 'Alice' }, { id: 'b', name: 'Bob' }];
const throws = (a,b) => ({kind:'cornhole',throws:{a,b},kiss:{a:0,b:0},jumpover:{a:0,b:0}});
assert(TOSSIT_MODES.length >= 13);
assert(TOSSIT_PLANNED.length >= 0, 'future TOSSIT variants remain visible in the catalog');
for (const mode of ['river','cornhole','goalkeeper','football_pitch']) assert(TOSSIT_MODES.some(m => m.id === mode), `${mode} registered`);

let river = newTossitGame('river', players, 6, 42);
river = move(river, {kind:'river',landings:[{kind:'opponent',points:4},{kind:'own',points:5},{kind:'miss',points:0},{kind:'miss',points:0},{kind:'miss',points:0},{kind:'miss',points:0}],kiss:1,jumpover:false});
assert.equal(river.scores.a,6,'opponent camp + Kiss bonus');
assert.equal(river.scores.b,5,'own camp awards opponents');
assert.equal(river.nextPlayerIndex,1);
river = move(river,{kind:'river',landings:[{kind:'opponent',points:2},{kind:'river',points:0}],kiss:0,jumpover:false});
assert.equal(river.scores.b,7,'river immediately ends turn');
assert.throws(() => move(river, {kind:'river',landings:[{kind:'river',points:0},{kind:'opponent',points:2}],kiss:0,jumpover:false}),/immediately/);
assert.throws(()=> move(river,{kind:'river',landings:[{kind:'miss',points:0}],kiss:0,jumpover:false}),/all darts/);
river=move(river,{kind:'river',landings:Array.from({length:6},()=>({kind:'opponent',points:10})),kiss:0,jumpover:true});
assert.equal(river.winnerId,'a','river target 50');
assert.equal(river.scores.b,0,'Jumpover resets opponents');
assert.equal(undo(river).winnerId,null,'river undo winner');
assert.throws(()=>newTossitGame('river',players,3),/setup/);
assert.equal(newTossitGame('river',players,9).dartsPerPlayer,9);

let corn = newTossitGame('cornhole',players,3,1);
assert.throws(()=>move(corn,throws(['hole','board'],['miss','miss','miss'])),/Invalid Cornhole/);
assert.throws(()=>move(corn,throws(['board','board','board','hole','hole','hole'],['miss','miss','miss'])),/perfect group/);
corn=move(corn,throws(['hole','hole','hole'],['miss','miss','miss']));
assert.equal(corn.scores.a,18,'three holes 9 + perfect set bonus 9');
corn=move(corn,throws(['board','miss','miss'],['miss','miss','miss']));
assert.equal(corn.scores.a,19);
const prior = corn;
corn=move(corn,throws(['board','board','board'],['miss','miss','miss']));
assert.equal(corn.scores.a,13,'over 21 resets to 13');
assert.equal(corn.cornholeBusted.a,true);
assert.equal(undo(corn).scores.a,19);
corn=move(corn,throws(['hole','hole','hole'],['miss','miss','miss']));
assert.equal(corn.scores.a,0,'second consecutive bust resets to zero');
const extra = move(newTossitGame('cornhole',players,3),throws(['hole','hole','hole','board','miss','miss'],['miss','miss','miss']));
assert.equal(extra.scores.a,19,'extra group after three holes is recorded');
let exactly = move(newTossitGame('cornhole',players,3),throws(['hole','hole','hole'],['miss','miss','miss']));
exactly = move(exactly,throws(['board','board','board'],['miss','miss','miss']));
assert.equal(exactly.winnerId,'a','21 exactly wins');
assert.equal(summaryForTossit(exactly).mode,'cornhole');
let canceled = move(newTossitGame('cornhole',players,3),throws(['hole','board','miss'],['hole','board','miss']));
assert.equal(canceled.scores.a,0,'equal round totals cancel');
assert.equal(canceled.scores.b,0);
let multiplier = move(newTossitGame('cornhole',players,3),{...throws(['board','board','miss'],['miss','miss','miss']),jumpover:{a:1,b:0}});
assert.equal(multiplier.scores.a,4,'Jumpover doubles base round score');

let keeper = newTossitGame('goalkeeper',players,3);
keeper=move(keeper,{kind:'goalkeeper',zones:[3,2,-1]});
assert.equal(keeper.scores.a,4);
assert.equal(keeper.nextPlayerIndex,1);
keeper=move(keeper,{kind:'goalkeeper',zones:[0,0,0]});
keeper=move(keeper,{kind:'goalkeeper',zones:[3,3,3]});
assert.equal(keeper.winnerId,'a','keeper first 11 wins');
assert.throws(()=>newTossitGame('goalkeeper',players,6),/setup/);

let pitch=newTossitGame('football_pitch',players,6);
assert.equal(pitch.pitch.attackerId,'a');
assert.throws(()=>move(pitch,{kind:'football_pitch',outcome:'goal'}),/centre first/);
pitch=move(pitch,{kind:'football_pitch',outcome:'centre'});
assert.equal(pitch.pitch.chainLength,1);
assert.equal(pitch.nextPlayerIndex,1);
pitch=move(pitch,{kind:'football_pitch',outcome:'block'});
assert.equal(pitch.pitch.blocks,1);
pitch=move(pitch,{kind:'football_pitch',outcome:'longpass'});
assert.equal(pitch.pitch.longPassUsed,true);
assert.throws(()=>move(pitch,{kind:'football_pitch',outcome:'linked'}),/role/);
pitch=move(pitch,{kind:'football_pitch',outcome:'miss'});
assert.throws(()=>move(pitch,{kind:'football_pitch',outcome:'longpass'}),/already used/);
pitch=move(pitch,{kind:'football_pitch',outcome:'goal'});
assert.equal(pitch.scores.a,1);
assert.equal(pitch.pitch.attackerId,'b','MSS roles rotate after goal');
assert.equal(pitch.pitch.drive,2);
assert.equal(pitch.nextPlayerIndex,1);
assert.equal(undo(pitch).pitch.attackerId,'a','pitch undo goal');
let exhaustion=newTossitGame('football_pitch',players,6);
for(let i=0;i<6;i++) {
 exhaustion=move(exhaustion,{kind:'football_pitch',outcome:'miss'});
 exhaustion=move(exhaustion,{kind:'football_pitch',outcome:'miss'});
}
assert.equal(exhaustion.pitch.drive,2,'six throws each, then new drive');
assert.equal(exhaustion.pitch.attackerId,'b','rotate after exhausted throws');
assert.equal(newTossitGame('football_pitch',players,6).dartsPerPlayer,6);
assert.throws(()=>newTossitGame('football_pitch',players,3),/setup/);
console.log('TOSSIT V142 Wave 4: River, Cornhole, Goalkeeper, Football Pitch — all assertions OK');
