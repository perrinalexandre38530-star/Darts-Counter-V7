// Exécuter : node --experimental-strip-types tools/test-morpion-top10-five-lives.mjs (Node >= 22)
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';
import { newMorpionGrid, applyMorpionVolley, morpionWinner } from '../src/lib/morpionEngine.ts';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const read = file => readFileSync(resolve(root,file),'utf8');
const board = newMorpionGrid(3, () => .375);
assert.equal(board.targets.length,9);
assert.equal(new Set(board.targets).size,9);
assert.equal(board.targets[4],25);
assert.ok(board.targets.every((n,i)=>i===4 || n>=1 && n<=20));
const hit=n=>({v:n,mult:1});
let x=applyMorpionVolley(board,0,[hit(board.targets[0]),{v:board.targets[0],mult:2},{v:board.targets[0],mult:3}]);
assert.equal(x.grid.owners[0],null,'Trois touches ne suffisent pas');
assert.equal(x.grid.marks[0][0],3,'Une touche simple/double/triple = une marque');
const rival=applyMorpionVolley(x.grid,1,[hit(board.targets[0])]);
assert.equal(rival.grid.marks[0][1],1,'Progression indépendante');
x=applyMorpionVolley(rival.grid,0,[hit(board.targets[0])]);
assert.equal(x.grid.owners[0],0,'La quatrième touche conquiert la case');
assert.equal(applyMorpionVolley(x.grid,1,[hit(board.targets[0])]).grid.marks[0][1],1,'Case verrouillée');
assert.equal(applyMorpionVolley(board,1,[{v:25,mult:2}]).grid.marks[4][1],1,'DBULL = touche au centre');
const owners = [0,0,0,null,null,null,null,null,null];
assert.equal(morpionWinner(owners),0,'Alignement horizontal');
const five=read('src/pages/FiveLivesPlay.tsx');
const fiveConfig=read('src/pages/FiveLivesConfig.tsx');
assert.match(five,/allowEqualScore \? score >= Number\(target\) : score > Number\(target\)/);
assert.match(fiveConfig,/startOrderMode === "bull" \|\| startOrderMode === "manual"/, 'BULL et MANUEL proposent le classement');
assert.match(fiveConfig,/startOrderSource: startOrderMode === "bull" \? "bull"/, 'origine BULL conservée dans la configuration');
assert.match(fiveConfig,/Variante des 5 vies/);
const registry=read('src/games/dartsGameRegistry.ts');
assert.match(registry,/id: "top_10"/);
assert.match(registry,/id: "top_10_training"/);
assert.match(registry,/id: "tic_tac_toe"/);
const app=read('src/App.tsx');
assert.match(app,/case "top_10_config"/);
assert.match(app,/case "top_10_play"/);
assert.match(app,/case "tic_tac_toe_play"/);
const top10=read('src/pages/Top10Play.tsx');
assert.match(top10,/const rounds = 10;/);
assert.match(top10,/createMatchCheckpointWriter\(\(rec: any\) => History\.upsert\(rec\)/);
assert.match(read('src/pages/PublicLandingPage.tsx'),/g\.id !== "top_10_training"/);
assert.match(read('src/pages/TrainingMenu.tsx'),/g\.id === "top_10_training" \? "top_10_config"/);
console.log('OK : 20 vérifications MORPION / TOP 10 / 5 VIES + navigation et historique');
