import assert from 'node:assert/strict';
import fs from 'node:fs';
import { canDistributeLandscapePanels } from '../src/components/gameplay/landscapeRoomPolicy.ts';
const read = path => fs.readFileSync(new URL('../'+path, import.meta.url), 'utf8');
const bridge = read('src/components/gameplay/LandscapePageFitBridge.tsx');
const css = read('src/styles/mss-landscape-fit-v248.css');
const mexican = read('src/pages/wave61/MexicainFiesta.css');
const play = read('src/pages/Wave61SharedPlay.tsx');
assert.equal(canDistributeLandscapePanels(900, [135, 175, 120], 14), true, 'distribute independent cards in a tall pane');
assert.equal(canDistributeLandscapePanels(500, [90, 90, 90], 10), true, 'moderate viewport with enough room');
assert.equal(canDistributeLandscapePanels(380, [130, 130, 90], 12), false, 'never squeeze a short viewport');
assert.equal(canDistributeLandscapePanels(900, [150], 10), false, 'never move a single active player to bottom');
assert.equal(canDistributeLandscapePanels(900, [150, 200], 10), false, 'keep two-panel mission layouts grouped');
assert.equal(canDistributeLandscapePanels(900, [100, 700], 10), false, 'never distribute an oversized panel');
assert.equal(canDistributeLandscapePanels(900, [500, 350], 10), false, 'never distribute content that fills the pane');
assert.equal(canDistributeLandscapePanels(900, [100, 100, 100, 100, 100, 100, 100]), false, 'too many tiles means gallery, not panels');
assert.match(bridge, /annotatePanelDistribution\(route, false\)/, 'clear on portrait and unmount');
assert.match(bridge, /annotatePanelDistribution\(route, roomWidth >= 840 && roomHeight >= 650\)/);
assert.doesNotMatch(bridge, /\[data-wave61-zone='mission'\]/);
assert.match(bridge, /panel\.querySelector\("\[data-mss-keypad/);
assert.match(css, /\[data-mss-landscape-distribute="grid"\]/);
assert.match(css, /\[data-mss-landscape-distribute="flex"\]/);
assert.doesNotMatch(css.slice(css.indexOf('/* V7(42)')), /grid-template-rows|min-height:\s*100%|transform:\s*scale/);
assert.match(mexican, /\.mex-landscape-roster\s*\{\s*display:\s*none/);
assert.match(mexican, /min-height:\s*650px/);
assert.match(play, /className="mex-landscape-roster"/);
assert.match(play, /VIES \/ POINTS VALIDÉS/);
console.log('PASS: landscape room policy, compact Mexicain roster, no keypad scaling and safe cleanup');
