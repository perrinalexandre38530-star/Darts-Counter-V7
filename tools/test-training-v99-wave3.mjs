import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { buildTrainingSessionInsight } from '../src/training/profile/trainingSessionInsights.ts';
const read = (name) => readFileSync(new URL('../' + name, import.meta.url), 'utf8');
const row = (exerciseId, performance, accuracy = 65, aggregatedDarts = 0) => ({exerciseId,title:exerciseId,performance,accuracy,darts:15,hits:10,aggregatedDarts,points:25,goal:30,completion:75,success:performance >= 70});
const card = (id, at, steps, overrides = {}) => ({id,at,kind:'program',title:'Séance X',count:steps.length,darts:45,performance:60,accuracy:65,successes:1,exercises:steps,...overrides});
const old = card('old',100,[row('double',75),row('finish',45)],{performance:60,accuracy:70,successes:1});
const newest = card('newest',200,[row('double',80),row('finish',60)],{performance:70,accuracy:75,successes:1});
const different = card('different',150,[row('bull',75),row('finish',45)],{performance:99,accuracy:99,successes:2});
const result = buildTrainingSessionInsight(newest,[newest,different,old]);
assert.equal(result.comparison?.previousAt,100,'Do not mix differing exercise protocols');
assert.equal(result.comparison?.performanceDelta,10);
assert.equal(result.comparison?.accuracyDelta,5);
assert.equal(result.weakest?.exerciseId,'finish');
assert.match(result.guidance,/finish/);
const aggregate = card('agg',300,[row('double',60,null,15)],{accuracy:null});
const aggResult = buildTrainingSessionInsight(aggregate,[aggregate,card('previous',200,[row('double',55)],{accuracy:66})]);
assert.equal(aggResult.comparison?.accuracyDelta,null,'No precision delta from aggregate-only darts');
assert.equal(aggResult.aggregatedDarts,15);
assert.equal(aggResult.preciseDarts,0);
const legacy = card('legacy',300,[{...row('double',null,null),darts:null}],{accuracy:null});
assert.equal(buildTrainingSessionInsight(legacy,[legacy]).weakest,null,'Do not infer a result from missing legacy step details');
assert.equal(buildTrainingSessionInsight(newest,[newest,different]).comparison,null,'Do not invent a comparable session');
const reversed = card('rev',100,[row('finish',45),row('double',75)],{performance:90});
assert.equal(buildTrainingSessionInsight(newest,[newest,reversed]).comparison,null,'Order must match');
const view = read('src/training/ui/TrainingSessionResultsCard.tsx');
const home = read('src/training/modes/lab/TrainingLabConfig.tsx');
const css = read('src/training/ui/trainingResponsive.css');
const resultModal = read('src/training/ui/TrainingResultModal.tsx');
assert.match(view,/buildTrainingSessionInsight/);
assert.match(view,/onNextAction/);
assert.match(view,/mssTrainingSessionExerciseTrack/);
assert.match(home,/trainingSessionCards\.map\(\(card, index\)/);
assert.match(home,/mssTrainingHubLastResult/);
assert.match(css,/mssTrainingResultSummary/);
assert.match(resultModal,/aria-modal="true"/);
console.log('Training V99 Wave 3: comparisons, missing precision, historical isolation, Awena action, and responsive result dialog: OK');
