import assert from 'node:assert/strict';
import { TOSSIT_MODES, TOSSIT_PLANNED, newTossitGame as fresh, applyTossitAction as play, undoTossitAction as undo, summaryForTossit } from '../src/pages/tossit/tossitEngine.ts';
const players=[{id:'a',name:'Alice'},{id:'b',name:'Bob'}];
assert.equal(TOSSIT_MODES.length,18,'18 playable modes');
assert(!TOSSIT_PLANNED.some(m=>['CHORES','CAPTURE THE BOTTLE'].includes(m.title)));
const dart=(effect,recipientId='b',chore='dishes')=>({effect,recipientId,chore});
let chores=fresh('chores',players,3,123,4,3);
assert.equal(chores.chores.b.length,0);
assert.throws(()=>play(chores,{kind:'chores',throws:[dart('chore')]}),/all three/);
assert.throws(()=>play(chores,{kind:'chores',throws:[dart('chore','bad'),dart('miss'),dart('miss')]}),/recipient/);
chores=play(chores,{kind:'chores',throws:[dart('chore'),dart('jumpover'),dart('miss')]});
assert.equal(chores.chores.b.length,3,'jumpover assigns two chores');
assert.equal(chores.scores.b,3,'pending chores count is displayed');
assert.equal(undo(chores).chores.b.length,0,'undo restores task ledger');
chores=play(chores,{kind:'chores',throws:[dart('kiss'),dart('double_trouble'),dart('free_day')]});
assert.equal(chores.chores.b.length,0,'free day clears all tasks');
for(let i=0;i<4;i++) chores=play(chores,{kind:'chores',throws:[dart('miss'),dart('miss'),dart('miss')]});
assert.equal(chores.finished,true); assert.equal(chores.winnerId,null);
assert.equal(summaryForTossit(chores).nonCompetitive,true);
assert.throws(()=>fresh('chores',players,4),/three darts/);
let solo=fresh('chores',[players[0]],3,123,4,3);
solo=play(solo,{kind:'chores',throws:[dart('chore','a'),dart('miss'),dart('miss')]});
assert.equal(solo.scores.a,1,'solo chore randomizer');
let bottle=fresh('bottle',players,3,456,4,3);
assert.throws(()=>play(bottle,{kind:'bottle',stuck:{a:1,b:0},onBottle:{a:2,b:0},closestPlayerId:'a'}),/Invalid Bottle/);
assert.throws(()=>play(bottle,{kind:'bottle',stuck:{a:0,b:1},onBottle:{a:0,b:0},closestPlayerId:'a'}),/no stuck/);
bottle=play(bottle,{kind:'bottle',stuck:{a:2,b:1},onBottle:{a:1,b:0},closestPlayerId:'b'});
assert.equal(bottle.scores.a,3); assert.equal(bottle.scores.b,1);
assert.equal(undo(bottle).scores.a,0);
bottle=play(bottle,{kind:'bottle',stuck:{a:0,b:0},onBottle:{a:0,b:0}});
assert.equal(bottle.scores.a,3);
bottle=play(bottle,{kind:'bottle',stuck:{a:2,b:0},onBottle:{a:2,b:0},closestPlayerId:'a'});
assert.equal(bottle.finished,true); assert.equal(bottle.winnerId,'a');
let tie=fresh('bottle',players,3,456,4,3);
for(let i=0;i<3;i++) tie=play(tie,{kind:'bottle',stuck:{a:0,b:0},onBottle:{a:0,b:0}});
assert.equal(tie.finished,true); assert.equal(tie.winnerId,null);
console.log('TOSSIT Wave6 regression OK (CHORES, BOTTLE, undo, invalid actions, end states)');
