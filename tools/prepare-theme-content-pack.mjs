import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';

const ROOT = process.cwd();
const THEME_SOURCE = path.join(ROOT, 'src', 'theme', 'themePresets.ts');
const PUBLIC_DIR = path.join(ROOT, 'public', 'theme-textures');
const RESTORED_DIR = path.join(ROOT, '.mss-theme-restore', 'theme-textures');
const OUT_DIR = path.join(ROOT, '.mss-content-packs-build', 'theme-textures');
const GENERATED_TS = path.join(ROOT, 'src', 'lib', 'contentPackCatalog.generated.ts');
const VERSION = '2026.09.03.2';
const MIN_EXPECTED = 110;
const SENTINELS = [
  'street-acier-urbain.webp',
  'factory-atelier-grunge.webp',
  'pub-bois-violet.webp',
  'arcade-pixel-rose.webp',
  'prestige-quartz-dore.webp',
  'abstract-orange-rugged.webp',
];

function ensureDir(dir) { fs.mkdirSync(dir, { recursive: true }); }
function sha256(file) { return crypto.createHash('sha256').update(fs.readFileSync(file)).digest('hex'); }
function mimeFor(rel) {
  const ext = path.extname(rel).toLowerCase();
  return ({ '.webp': 'image/webp', '.svg': 'image/svg+xml', '.png': 'image/png', '.jpg': 'image/jpeg', '.jpeg': 'image/jpeg' })[ext] || 'application/octet-stream';
}
function validAsset(file) {
  try {
    const data = fs.readFileSync(file);
    const ext = path.extname(file).toLowerCase();
    if (data.length < 16) return false;
    if (ext === '.webp') return data.subarray(0, 4).toString('ascii') === 'RIFF' && data.subarray(8, 12).toString('ascii') === 'WEBP';
    if (ext === '.svg') return data.toString('utf8', 0, Math.min(data.length, 1024)).includes('<svg');
    return true;
  } catch { return false; }
}
function requiredTextures() {
  const source = fs.readFileSync(THEME_SOURCE, 'utf8');
  const refs = [...new Set([...source.matchAll(/\/theme-textures\/([^)'"\s,]+)/g)].map((m) => m[1]))].sort();
  const parserMissing = SENTINELS.filter((file) => !refs.includes(file));
  if (parserMissing.length) throw new Error(`Analyse des textures invalide: ${parserMissing.join(', ')}`);
  if (refs.length < MIN_EXPECTED) throw new Error(`Analyse des textures incomplete: ${refs.length} detectee(s), minimum attendu ${MIN_EXPECTED}.`);
  return refs;
}
function locateSource(rel) {
  const candidates = [path.join(PUBLIC_DIR, rel), path.join(RESTORED_DIR, rel)];
  return candidates.find(validAsset) || null;
}
function readCatalog() {
  const source = fs.readFileSync(GENERATED_TS, 'utf8');
  const prefix = 'export const CONTENT_PACK_CATALOG = ';
  const start = source.indexOf(prefix);
  const end = source.lastIndexOf(' as const;');
  if (start < 0 || end < 0) throw new Error('Impossible de lire contentPackCatalog.generated.ts');
  return JSON.parse(source.slice(start + prefix.length, end));
}
function writeCatalog(catalog) {
  const source = `/* AUTO-GENERATED by tools/prepare-content-packs.mjs. Do not edit manually. */\n` +
    `export const CONTENT_PACK_CATALOG = ${JSON.stringify(catalog, null, 2)} as const;\n` +
    `export type GeneratedContentPackId = keyof typeof CONTENT_PACK_CATALOG;\n`;
  fs.writeFileSync(GENERATED_TS, source);
}

const required = requiredTextures();
const sources = new Map(required.map((rel) => [rel, locateSource(rel)]));
const missing = required.filter((rel) => !sources.get(rel));
if (missing.length) {
  throw new Error(`Theme pack incomplet: ${missing.length} texture(s) manquante(s). Lance d'abord: npm run themes:restore\n${missing.join('\n')}`);
}

fs.rmSync(OUT_DIR, { recursive: true, force: true });
ensureDir(OUT_DIR);
const files = [];
for (const rel of required) {
  const src = sources.get(rel);
  const dest = path.join(OUT_DIR, ...rel.split('/'));
  ensureDir(path.dirname(dest));
  fs.copyFileSync(src, dest);
  files.push({ path: rel, bytes: fs.statSync(dest).size, sha256: sha256(dest), mime: mimeFor(rel) });
}

const manifest = { id: 'theme-textures', version: VERSION, files, totalBytes: files.reduce((n, f) => n + f.bytes, 0) };
fs.writeFileSync(path.join(OUT_DIR, 'manifest.json'), JSON.stringify(manifest, null, 2));

const catalog = readCatalog();
catalog['theme-textures'] = {
  version: VERSION,
  totalBytes: manifest.totalBytes,
  files: files.map(({ path: filePath, bytes }) => ({ path: filePath, bytes })),
};
writeCatalog(catalog);

console.log(`Theme textures referencees : ${required.length}`);
console.log(`Theme textures publiees    : ${files.length}`);
console.log(`Version R2                  : ${VERSION}`);
console.log(`Taille                      : ${(manifest.totalBytes / 1024 / 1024).toFixed(2)} MB`);
console.log('OK - pack theme-textures complet; les autres versions de packs ne sont pas modifiees.');
