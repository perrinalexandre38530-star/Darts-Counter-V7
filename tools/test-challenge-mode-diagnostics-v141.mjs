import assert from 'node:assert/strict';
import fs from 'node:fs';
import {buildChallengeModeDiagnostics} from '../src/lib/challengeModeDiagnostics.ts';
import {CHALLENGE_MODE_OPTIONS} from '../src/lib/challengeUnifiedCatalog.ts';
const make=(id,modeId,config,entries,extra={})=>({id,modeId,title:modeId,configKey:JSON.stringify(config),configLabel:'test',playedAt:1000,score:100,darts:entries?.length||0,successful:0,accuracy:0,bestStreak:0,status:'finished',playerId:'P1',playerName:'Test',record:{summary:{perPlayer:[{id:'P1',name:'Test'}]},payload:{config,entries}},...extra});
assert.equal(CHALLENGE_MODE_OPTIONS.length,51);
const c={catalogChallengeId:'perfect-line',catalogLine:20,catalogVariant:'classic',catalogRounds:5};
const steps=[['D',20],['G',20],['T',20],['P',20],['BULL',null],['DBULL',null]];
const hits=[{pid:'P1',zone:'MISS',segment:null},...steps.map(([zone,segment])=>({pid:'P1',zone,segment}))];
const good=make('arc1','arcade:perfect-line',c,hits);
const other=make('other','arcade:perfect-line',c,[{pid:'P2',zone:'D',segment:20}],{playerId:'P2',record:{summary:{perPlayer:[{id:'P1'},{id:'P2'}]},payload:{config:c,entries:[...hits,...[{pid:'P2',zone:'D',segment:20}]]}}});
const ongoing={...good,id:'unfinished',status:'in_progress'};
const report=buildChallengeModeDiagnostics([good,ongoing],'arcade:perfect-line');
assert.equal(report.finished,1);
assert.equal(report.documented,1);
assert.equal(report.darts,7);
assert.equal(report.successes,6);
assert.equal(report.failures,1);
assert.equal(report.objectives.length,6);
assert.equal(report.objectives.find(o=>o.label==='D20').attempts,2);
assert.equal(report.objectives.find(o=>o.label==='D20').validated,1);
assert.ok(report.cards.some(x=>x.label==='OBJECTIFS VALIDÉS'));
assert.ok(report.recordCards.some(x=>x.label==='PRÉCISION MAXIMALE'));
const legacyConfig={exerciseType:'classic',target:'20',rule:'all',visits:2};
const classicHits=[{pid:'P1',hit:'S',segment:20},{pid:'P1',hit:'D',segment:20},{pid:'P1',hit:'T',segment:20},{pid:'P1',hit:'MISS',segment:null},{pid:'P1',hit:'MISS',segment:null},{pid:'P1',hit:'MISS',segment:null}];
const classic=buildChallengeModeDiagnostics([make('c1','classic',legacyConfig,classicHits)],'classic');
assert.equal(classic.documented,1);
assert.equal(classic.darts,6);
assert.equal(classic.successes,3);
assert.equal(classic.failures,3);
assert.equal(classic.validatedVisits,1);
assert.equal(classic.perfectVisits,1);
assert.ok(classic.objectives.length>0);
const hidden=buildChallengeModeDiagnostics([{...good,record:{summary:{perPlayer:[{id:'P1'}]},payload:{config:c}}}],'arcade:perfect-line');
assert.equal(hidden.missing,1);
assert.equal(hidden.documented,0);
assert.equal(hidden.cards.length,0);
const contaminated=buildChallengeModeDiagnostics([other],'arcade:perfect-line');
assert.equal(contaminated.documented,1);
assert.equal(contaminated.darts,1,'only the selected player’s dart may be counted');
const missingIdentity=buildChallengeModeDiagnostics([make('noid','arcade:perfect-line',c,hits.map(({zone,segment})=>({zone,segment})),{record:{summary:{perPlayer:[{id:'P1'},{id:'P2'}]},payload:{config:c,entries:hits.map(({zone,segment})=>({zone,segment}))}}})],'arcade:perfect-line');
assert.equal(missingIdentity.documented,0,'unattributed multiplayer hits must not be used');
const exactConfig={catalogChallengeId:'exact-count',catalogLine:20,catalogVariant:'classic',catalogRounds:2,catalogTarget:100};
const exactDarts=[{pid:'P1',zone:'T',segment:20},{pid:'P1',zone:'D',segment:20},{pid:'P1',zone:'MISS',segment:null},
 {pid:'P1',zone:'G',segment:1},{pid:'P1',zone:'G',segment:1},{pid:'P1',zone:'G',segment:1}];
const exact=buildChallengeModeDiagnostics([make('count','arcade:exact-count',exactConfig,exactDarts)],'arcade:exact-count');
assert.ok(exact.cards.some(card=>card.label==='VOLÉES RÉUSSIES'&&card.value==='1'),'exact-score challenge must not count nonzero failed volleys');
assert.equal(exact.objectives.find(row=>row.label==='VOLÉE 1')?.validated,1);
assert.equal(exact.objectives.find(row=>row.label==='VOLÉE 2')?.validated,0,'scoring must validate the target total, not non-MISS hits');
const distinctConfig={...exactConfig,catalogTarget:120};
const separated=buildChallengeModeDiagnostics([make('count','arcade:exact-count',exactConfig,exactDarts)],'arcade:exact-count');
assert.equal(separated.documented,1,'stats are calculated from filtered selected configuration only');
assert.notDeepEqual(distinctConfig,exactConfig);
const ui=fs.readFileSync('src/components/challenge/ChallengeInsightsPage.tsx','utf8');
assert.match(ui,/ChallengeModeDiagnosticsUI modeId=\{modeId\} items=\{filtered\} view="stats"/);
assert.match(ui,/items=\{all.filter\(row=>row.configKey===selectedRecordsGroup.key\)\} view="records"/);
assert.ok(!ui.includes('Math.random'), 'no fabricated chart data');
console.log('✅ CHALLENGE V141: dedicated mode stats, archive boundaries, exact objectives, records by config, no invented sessions');
