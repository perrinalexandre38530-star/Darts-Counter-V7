import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import ts from 'typescript';
const read = path => readFileSync(new URL('../' + path, import.meta.url), 'utf8');
const files = ['src/lib/capitalStatsHistory.ts','src/components/stats/CapitalStatsTabFull.tsx','src/pages/CapitalPlay.tsx','src/pages/HistoryPage.tsx'];
let compiled = '';
for (const file of files) {
  const out = ts.transpileModule(read(file), { fileName:file, reportDiagnostics:true, compilerOptions:{ module:ts.ModuleKind.ESNext, target:ts.ScriptTarget.ES2022, jsx:ts.JsxEmit.ReactJSX }});
  assert.equal(out.diagnostics.filter(d=>d.category === ts.DiagnosticCategory.Error).length, 0, `Syntaxe ${file}`);
  if (file === files[0]) compiled = out.outputText;
}
const {capitalCompletedMatches,capitalHistoryVariant,isCompletedCapitalRecord,findCapitalHistoryPlayer} = await import('data:text/javascript;charset=utf-8,'+encodeURIComponent(compiled));
const players = [{id:'ninja',profileId:'ninja',name:'Ninja',finalCapital:200,successfulContracts:2,failedContracts:1},{id:'alex',name:'Alex',finalCapital:120}];
const finished=(id,variant='clubs15',winner='ninja')=>({id,matchId:id,kind:'capital',status:'finished',updatedAt:8,config:{gridVariant:variant},players, winnerIds:[winner],summary:{mode:'capital',finishedAt:4,players}});
const live={...finished('live'),status:'in_progress',summary:{mode:'capital',players}};
assert.equal(isCompletedCapitalRecord(live),false);
assert.equal(isCompletedCapitalRecord(finished('done')),true);
assert.equal(isCompletedCapitalRecord({id:'other',kind:'x01',status:'finished'}),false);
assert.equal(findCapitalHistoryPlayer(finished('x'),'ninja','Alex').name,'Ninja');
assert.equal(findCapitalHistoryPlayer(finished('x'),'unknown','Alex'),null,'Même nom et ID différent ne doit pas être attribué');
assert.deepEqual(capitalHistoryVariant(finished('x','expert')),{id:'expert',label:'EXPERT'});
assert.deepEqual(capitalHistoryVariant({...finished('custom'),config:{mode:'custom',savedVariantId:'own1',savedVariantName:'Capital du jeudi'}}),{id:'custom:own1',label:'Capital du jeudi'});
const records=[live,finished('a'),{...finished('a'),updatedAt:3},finished('b','expert'),finished('c','legends'),finished('d','beginner','alex')];
const matches=capitalCompletedMatches(records,'ninja','Ninja');
assert.equal(matches.length,4,'4 parties uniques terminées seulement');
assert.equal(matches.filter(x=>x.variantId==='clubs15').length,1);
assert.equal(matches.filter(x=>x.variantId==='expert').length,1);
assert.equal(matches.filter(x=>x.variantId==='legends').length,1);
assert.equal(matches.filter(x=>x.variantId==='beginner').length,1);
assert(!matches.some(x=>x.record.id==='live'));
const play=read('src/pages/CapitalPlay.tsx'),history=read('src/pages/HistoryPage.tsx'),stats=read('src/components/stats/CapitalStatsTabFull.tsx');
assert.match(play,/const capitalVariant =/);
assert.match(play,/capitalVariant,\n\s*participantMode/);
assert.match(play,/mode: "capital",\n\s*capitalVariant,/);
assert.match(history,/VARIANTE · \{variantName\}/);
assert.match(stats,/capitalCompletedMatches\(/);
assert.match(stats,/setVariantFilter/);
assert.match(stats,/Seules les parties terminées sont comptées/);
console.log('CAPITAL V158 : uniquement nouvelles parties terminées, identités strictes, anti-doublons, bilan par variante et Historique V4 OK.');
