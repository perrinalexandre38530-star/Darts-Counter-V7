import assert from 'node:assert/strict';
import { newTossitGame, applyTossitAction, undoTossitAction, summaryForTossit, ticTacHasLine } from '../src/pages/tossit/tossitEngine.ts';
const players = [{ id: 'alice', name: 'Alice' }, { id: 'bob', name: 'Bob' }];
let state = newTossitGame('classic', players, 3, 1);
state = applyTossitAction(state, { kind: 'classic', playerId: 'alice', closestDarts: 2, kiss: 0, jackiss: false, jackissExtra: 0, jumpover: false, jackover: false });
assert.equal(state.scores.alice, 2);
assert.equal(state.events.length, 1);
assert.equal(undoTossitAction(state).scores.alice, 0);
state = applyTossitAction(state, { kind: 'classic', playerId: 'bob', closestDarts: 1, kiss: 1, jackiss: true, jackissExtra: 2, jumpover: true, jackover: false });
assert.equal(state.scores.alice, 0, 'jumpover resets opponents');
assert.equal(state.scores.bob, 17, 'classic Kiss +2 bonuses');
assert.equal(state.winnerId, 'bob');
assert.equal(summaryForTossit(state).mode, 'classic');
assert.throws(() => applyTossitAction(state, { kind: 'classic', playerId: 'alice', closestDarts: 1, kiss: 0, jackiss: false, jackissExtra: 0, jumpover: false, jackover: false }));
let direct = newTossitGame('classic', players);
direct = applyTossitAction(direct, { kind: 'classic', playerId: 'alice', closestDarts: 0, kiss: 0, jackiss: false, jackissExtra: 0, jumpover: false, jackover: true });
assert.equal(direct.winnerId, 'alice', 'jackover wins instantly');
let target = newTossitGame('target', players);
target = applyTossitAction(target, { kind: 'target', hits: [3, 3, 3] });
assert.equal(target.scores.alice, 10, 'all stuck +1');
target = applyTossitAction(target, { kind: 'target', hits: [1, 0, 0] });
assert.equal(target.scores.bob, 1);
target = applyTossitAction(target, { kind: 'target', hits: [3, 3, 3] });
assert.equal(target.scores.alice, 20);
target = applyTossitAction(target, { kind: 'target', hits: [0, 0, 0] });
target = applyTossitAction(target, { kind: 'target', hits: [3, 0, 0] });
assert.equal(target.scores.alice, 20, 'overshoot preserves prior score');
target = applyTossitAction(target, { kind: 'target', hits: [0, 0, 0] });
target = applyTossitAction(target, { kind: 'target', hits: [1, 0, 0] });
assert.equal(target.winnerId, 'alice', 'exact 21 wins');
let speed = newTossitGame('speed', players);
speed = applyTossitAction(speed, { kind: 'speed', stuck: {alice: 3, bob: 0}, kiss: {alice: 1,bob: 0} });
assert.equal(speed.scores.alice, 4);
assert.equal(speed.scores.bob, -4, 'zero-stick penalty');
speed = applyTossitAction(speed, { kind: 'speed', stuck: {alice: 0,bob: 1},kiss: {alice: 0,bob: 0},jumpoverWinnerId:'bob' });
assert.equal(speed.winnerId, 'bob', 'Speed Jumpover instant win');
assert.throws(() => newTossitGame('speed', [{id:'x',name:'X'}]));
// V132: full scoring for the three newly playable official rule modes.
let classicFrench = newTossitGame('classic', players, 3);
classicFrench = applyTossitAction(classicFrench, {kind:'classic', playerId:'alice', closestDarts:3, kiss:1, frenchKiss:1, jackiss:false, jackissExtra:0, jumpover:false, jackover:false});
assert.equal(classicFrench.scores.alice, 8, 'Classic Kiss +2 and French Kiss +3');
assert.throws(() => newTossitGame('duel', players, 3), /six/);
let duel = newTossitGame('duel', players, 6);
duel = applyTossitAction(duel, {kind:'duel',stuck:6,jackStuck:false,kiss:2,jumpover:1});
assert.equal(duel.scores.alice,0,'missing black jack is zero');
assert.equal(duel.nextPlayerIndex,1,'duel alternates');
duel = applyTossitAction(duel, {kind:'duel',stuck:5,jackStuck:true,kiss:2,jumpover:1});
assert.equal(duel.scores.bob,10,'Duel bonus: 5 +2 +3');
duel = applyTossitAction(duel, {kind:'duel',stuck:6,jackStuck:true,kiss:1,jumpover:2});
assert.equal(duel.scores.alice,13);
duel = applyTossitAction(duel, {kind:'duel',stuck:6,jackStuck:true,kiss:1,jumpover:2});
assert.equal(duel.winnerId,'bob','duel first to 21');
assert.equal(undoTossitAction(duel).winnerId,null,'duel undo win');
let border = newTossitGame('border', players);
border = applyTossitAction(border, {kind:'border',valid:{alice:[2,4,9],bob:[6,7]},wrongSide:{alice:0,bob:1}});
assert.equal(border.scores.alice,3,'2 closer darts + opponent wrong side');
assert.equal(border.scores.bob,0);
border = applyTossitAction(border, {kind:'border',valid:{alice:[3],bob:[1,2]},wrongSide:{alice:2,bob:0}});
assert.equal(border.scores.bob,4,'2 closer darts + two penalties');
assert.throws(() => applyTossitAction(border,{kind:'border',valid:{alice:[3,4,5,6],bob:[]},wrongSide:{alice:0,bob:0}}));
let tictac = newTossitGame('tictac',players,3,12,4);
for(const cell of [0,4,1,5,2]) tictac = applyTossitAction(tictac,{kind:'tictac',cell});
assert.equal(tictac.winnerId,'alice','4x4 connect-three');
assert.equal(tictac.scores.alice,3,'occupied cells counted');
assert.equal(undoTossitAction(tictac).winnerId,null,'undo board win');
assert.throws(() => applyTossitAction(tictac,{kind:'tictac',cell:9}),/finished/);
let occupied = newTossitGame('tictac',players,3,12,4);
occupied = applyTossitAction(occupied,{kind:'tictac',cell:3});
occupied = applyTossitAction(occupied,{kind:'tictac',cell:3});
assert.equal(occupied.board[3],'alice','occupied cell not stolen');
assert.equal(occupied.nextPlayerIndex,0,'turn passes on occupied cell');
assert.equal(occupied.scores.bob,0,'no points for occupied cell');
const diag = Array(25).fill(null); for(const index of [4,8,12,16]) diag[index]='alice';
assert.equal(ticTacHasLine(diag,5,'alice'),true,'5x5 diagonal connect-four');
assert.equal(ticTacHasLine(diag,5,'bob'),false);
assert.throws(() => newTossitGame('tictac', [{id:'one',name:'Only'}]));
assert.throws(() => newTossitGame('tictac',players,3,1,3));
assert.equal(summaryForTossit(occupied).gridSize,4);
console.log('TOSSIT engine: classic, speed, target, duel, border & tic-tac assertions OK');
// V136 rebase wave 3: Battle Mode, El Sniper, Color Conquest.
let battle = newTossitGame('battle', players, 3, 14, 4, 3);
assert.equal(battle.victoryTarget, 3, 'Battle match format configurable');
assert.throws(() => applyTossitAction(battle, { kind:'battle', stuck:{alice:2,bob:2},jackStuck:true,closestPlayerId:'alice'}),/rock-paper/);
assert.throws(() => applyTossitAction(battle, { kind:'battle', stuck:{alice:3,bob:0},jackStuck:true,closestPlayerId:'bob'}),/stuck coloured/);
battle = applyTossitAction(battle, { kind:'battle', stuck:{alice:3,bob:2}, jackStuck:false });
assert.equal(battle.scores.alice, 0, 'Missed jack cannot award a round');
battle = applyTossitAction(battle, { kind:'battle', stuck:{alice:2,bob:2}, tieWinnerId:'bob', jackStuck:true, closestPlayerId:'alice' });
assert.equal(battle.scores.alice, 1, 'Closest colour can beat the player who threw the jack');
assert.match(battle.events.at(-1).explanation, /Bob lance la noire/);
assert.equal(undoTossitAction(battle).scores.alice, 0);
battle = applyTossitAction(battle, { kind:'battle', stuck:{alice:2,bob:1}, jackStuck:true, closestPlayerId:'alice' });
battle = applyTossitAction(battle, { kind:'battle', stuck:{alice:3,bob:1}, jackStuck:true, closestPlayerId:'alice' });
assert.equal(battle.winnerId, 'alice', 'First to three round victories, not dart points');
assert.equal(summaryForTossit(battle).victoryTarget, 3);
assert.throws(() => newTossitGame('battle', players, 3, 1, 4, 2),/Invalid MSS match target/);
assert.throws(() => newTossitGame('battle', [...players, {id:'c',name:'Carol'}]),/two players/);
let sniper = newTossitGame('sniper', [...players, {id:'carol',name:'Carol'}]);
sniper = applyTossitAction(sniper,{kind:'sniper',outcome:'miss'});
assert.equal(sniper.finished,false,'No automatic victory for a failed stack');
assert.throws(() => applyTossitAction(sniper,{kind:'sniper',outcome:'mega',playerId:'nobody'}),/Sniper winner/);
sniper = applyTossitAction(sniper,{kind:'sniper',outcome:'ultimate',playerId:'carol'});
assert.equal(sniper.winnerId,'carol','Ultimate double stack wins immediately');
assert.equal(sniper.scores.carol,1,'Instant modes record one win, not 13 points');
assert.equal(undoTossitAction(sniper).finished,false,'Undo instant win before saving');
let conquest = newTossitGame('conquest', players, 3, 1, 4, 3);
conquest = applyTossitAction(conquest,{kind:'conquest',color:'Rouge',required:3,stuck:{alice:2,bob:1}});
assert.equal(conquest.scores.alice,0,'No team reached the required amount');
assert.throws(() => applyTossitAction(conquest,{kind:'conquest',color:'Rouge',required:3,stuck:{alice:3,bob:3}}),/completed the target first/);
assert.throws(() => applyTossitAction(conquest,{kind:'conquest',color:'Orange',required:3,stuck:{alice:3,bob:0}}),/Invalid Color/);
conquest = applyTossitAction(conquest,{kind:'conquest',color:'Bleu',required:2,stuck:{alice:2,bob:2},firstId:'bob'});
assert.equal(conquest.scores.bob,1,'First to complete wins the round');
conquest = applyTossitAction(conquest,{kind:'conquest',color:'Rose',required:2,stuck:{alice:0,bob:2}});
conquest = applyTossitAction(conquest,{kind:'conquest',color:'Vert',required:1,stuck:{alice:0,bob:1}});
assert.equal(conquest.winnerId,'bob','Conquest MSS first to 3 rounds');
assert.equal(summaryForTossit(conquest).victoryTarget,3);
console.log('TOSSIT V136 wave 3: 3 modes, instant wins, ties, round targets, invalid actions and undo OK');
