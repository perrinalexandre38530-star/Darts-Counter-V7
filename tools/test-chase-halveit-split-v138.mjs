assert.match(router,/gamesCategory: "variant"/);
assert.match(text('src/games/dartsPublicRulesAudit.ts'),/GAMES > VARIANTES/);
// Gameplay tests: shared engine supports distinct game flows.
const p=[{id:'p1',name:'P1'},{id:'p2',name:'P2'}];
const miss={bed:'MISS'};
const classic={participantMode:'players',sequencePreset:'classic7',startMode:'zero',fixedStartingScore:40,rounding:'floor'};
let s=createHalveItState(p, classic, [], ['p1','p2']);
assert.deepEqual(s.targets.map(x=>x.id), halveItPresetTargets('classic7'));
assert.equal(s.targets.length,7);
assert.deepEqual(s.scoresByPlayer,{p1:0,p2:0});
s=playHalveItVisit(s,[{bed:'T',number:20},miss,miss]);
assert.equal(s.scoresByPlayer.p1,60);
s=playHalveItVisit(s,[miss,miss,miss]);
assert.equal(s.roundIndex,1, 'the two players have visited the same target before proceeding');
s=playHalveItVisit(s,[miss,miss,miss]);
assert.equal(s.scoresByPlayer.p1,30, 'halve-it penalty on failed visit');
let team=createHalveItState(p,{...classic, participantMode:'teams',startMode:'fixed',fixedStartingScore:40},[{id:'team1',name:'Team 1',playerIds:['p1']},{id:'team2',name:'Team 2',playerIds:['p2']}]);
assert.equal(team.standings.length,2);
assert.equal(team.standings[0].score,40);
team=playHalveItVisit(team,[{bed:'D',number:20},{bed:'T',number:20},miss]);
assert.equal(team.scoresByPlayer.p1,140);
assert.equal(team.standings[0].score,140);
let opening=createHalveItState([{id:'solo',name:'Solo'}],{...classic,startMode:'opening_visit'});
assert.equal(opening.targets[0].id,'open');
opening=playHalveItVisit(opening,[miss,miss,miss]);
assert.equal(opening.scoresByPlayer.solo,0);
assert.equal(opening.statsByPlayer.solo.halvingEvents,0,'opening visit does not halve');
assert.equal(halveItTargetScore(targetFromId('double_any'),{bed:'IB'}),50);
assert.equal(halveItTargetScore(targetFromId('bull'),{bed:'OB'}),25);
const split=['n15','n16','double_any','n17','n18','triple_any','n19','n20','bull'];
const rules={...classic,startMode:'fixed',fixedStartingScore:40,customTargets:split};
let ss=createHalveItState(p,rules);
assert.deepEqual(ss.targets.map(t=>t.id),split);
ss=playHalveItVisit(ss,[miss,miss,miss]);
assert.equal(ss.scoresByPlayer.p1,20);
assert.match(halve,/fixedStartingScore: isSplitScore \? 40 : fixedStartingScore/);
assert.match(halve,/customTargets: \[\.\.\.SPLIT_SCORE_TARGETS\]/);
