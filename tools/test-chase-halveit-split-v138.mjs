import { createHalveItState, playHalveItVisit, halveItPresetTargets, halveItTargetScore, targetFromId } from '../src/lib/gameEngines/halveItEngine.ts';
const base=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const text=(name)=>readFileSync(resolve(base,name),'utf8');
const gameDefs=text('src/games/dartsGameRegistry.ts');
const extractGame=(id)=>{const start=gameDefs.indexOf(`id: "${id}",`);assert.ok(start>0,id+' in registry');return gameDefs.slice(start,gameDefs.indexOf('\n  },',start)+5)};
assert.match(extractGame('five_lives'),/category: "classic"/);
assert.match(extractGame('chase'),/category: "variant"/);
assert.match(extractGame('halve_it'),/category: "challenge"/);
assert.match(extractGame('split_score'),/category: "variant"/);
for (const id of ['five_lives','chase','halve_it','split_score']) {
  assert.match(extractGame(id),/ready: true/);
  assert.match(text('src/config/androidStoreV1.ts'),new RegExp(`"${id}"`));
}
assert.match(gameDefs, /"halve_it", \/\/ moteur HALVE-IT opérationnel/);
const router=text('src/App.tsx');
const bridge=text('src/components/DartsModeFamilyBridge.tsx');
const five=text('src/pages/FiveLivesConfig.tsx');
const halve=text('src/pages/HalveItConfig.tsx');
const entry=text('src/components/GameModeEntryChoice.tsx');
const games=text('src/pages/Games.tsx');
assert.match(router, /key="five-lives-chase"/);
assert.match(router, /key="five-lives-main"/);
assert.match(router, /key="halve-it-split-score"/);
