// Run with: node --experimental-strip-types tools/test-awena-academy-v166.mjs
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
const { applyAcademyVisit, newAcademyRun, academyResultScore } = await import('../src/training/academy/academyCore.ts');
const dart = (v, mult=1) => ({ v, mult, score: v*mult, label: `${mult===3?'T':mult===2?'D':'S'}${v}`, miss: v===0, bull: false, dbull:false });
const checkout = {kind:'checkout',start:46,maxDarts:6};
let x = applyAcademyVisit(checkout,newAcademyRun(checkout),[dart(14), dart(16,2), dart(4)]);
assert.equal(x.won,true); assert.equal(x.darts,2); assert.equal(x.remaining,0);
assert.equal(academyResultScore(true,x,checkout),100);
const bust = {kind:'checkout',start:24,maxDarts:6};
x = applyAcademyVisit(bust,newAcademyRun(bust),[dart(4),dart(8,3),dart(10)]);
assert.equal(x.remaining,24); assert.equal(x.darts,2); assert.equal(x.busts,1);
x = applyAcademyVisit(bust,x,[dart(12,2)]); assert.equal(x.won,true); assert.equal(x.darts,3);
const odd = {kind:'checkout',start:2,maxDarts:3};
x = applyAcademyVisit(odd,newAcademyRun(odd),[dart(1)]);
assert.equal(x.remaining,2); assert.equal(x.busts,1);
const target = {kind:'target',target:'D20',maxDarts:3};
x = applyAcademyVisit(target,newAcademyRun(target),[dart(20),dart(20,2),dart(20)]);
assert.equal(x.won,true); assert.equal(x.darts,2);
x = applyAcademyVisit(target,x,[dart(20,2)]); assert.equal(x.darts,2);
const last = {kind:'target',target:'T20',maxDarts:3};
x = applyAcademyVisit(last,newAcademyRun(last),[dart(1),dart(2),dart(3)]);
assert.equal(x.ended,true); assert.equal(x.won,false); assert.equal(x.darts,3);
const backing = new Map();
globalThis.localStorage = { getItem: k => backing.get(k) ?? null, setItem: (k,v) => backing.set(k,String(v)) };
const { loadAcademyProgress, saveAcademyAttempt } = await import('../src/training/academy/academyStore.ts');
saveAcademyAttempt('player-1','reading-board',{score:100,quizCorrect:true,practiceWon:true,darts:2,busts:0});
saveAcademyAttempt('player-1','reading-board',{score:30,quizCorrect:true,practiceWon:false,darts:6,busts:0});
assert.equal(loadAcademyProgress('player-1')['reading-board'].best,100);
assert.equal(loadAcademyProgress('player-1')['reading-board'].attempts,2);
assert.equal(Object.keys(loadAcademyProgress('player-2')).length,0);
const lessons = readFileSync(new URL('../src/training/academy/academyLessons.ts', import.meta.url),'utf8');
assert.equal((lessons.match(/id: "[a-z-]+", level:/g)||[]).length, 10);
const lab = readFileSync(new URL('../src/training/modes/lab/TrainingLabConfig.tsx',import.meta.url),'utf8');
assert.ok(lab.includes('tab === "academy"') && lab.includes('TrainingAwenaAcademy'));
console.log('MSS Academy V166: 10 lessons, bust/finish/count + profile persistence tests, wiring OK');
