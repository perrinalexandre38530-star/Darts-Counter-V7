#!/usr/bin/env node
import fs from "node:fs";
const read=(p)=>fs.readFileSync(p,"utf8");
const must=(ok,msg)=>{ if(!ok){console.error(`❌ ${msg}`);process.exit(1)} console.log(`✅ ${msg}`); };
const master=read("src/awena/AwenaMasterKnowledgeV89.ts");
const proc=read("src/awena/AwenaProceduralV89.ts");
const academy=read("src/awena/AwenaProceduralAcademy.ts");
const core=read("src/awena/AwenaCore.ts");
const overlay=read("src/awena/components/AwenaOverlay.tsx");
const pkg=JSON.parse(read("package.json"));
const entries=[...master.matchAll(/\n\s*id:\s*"(v89-[^"]+)"/g)].map(m=>m[1]);
const domains=[...master.matchAll(/domain:\s*"([^"]+)"/g)].map(m=>m[1]);
const aliases=[...master.matchAll(/aliases:\s*(\[[^\n]+\])/g)].reduce((n,m)=>{try{return n+JSON.parse(m[1]).length}catch{return n}},0);
const procedures=[...proc.matchAll(/\n\s*id:\s*"(v89-[^"]+)"/g)].map(m=>m[1]);
const steps=[...proc.matchAll(/steps:\s*(\[[^\n]+\])/g)].reduce((n,m)=>{try{return n+JSON.parse(m[1]).length}catch{return n}},0);
const trouble=[...proc.matchAll(/troubleshooting:\s*(\[[^\n]+\])/g)].reduce((n,m)=>{try{return n+JSON.parse(m[1]).length}catch{return n}},0);
must(entries.length >= 350, `Master Knowledge depth: ${entries.length} new topics`);
must(new Set(domains).size >= 15, `Master Knowledge breadth: ${new Set(domains).size} domains`);
must(aliases >= 600, `Master Knowledge vocabulary: ${aliases} aliases/phrasings`);
must(procedures.length >= 40, `V8.9 procedural extension: ${procedures.length} new tutorials`);
must(steps >= 220, `V8.9 procedural detail: ${steps} guided steps`);
must(trouble >= 55, `V8.9 troubleshooting branches: ${trouble}`);
for (const needle of ["Google Play Console","Row Level Security","ANR","First 9 Average","Oche","Carreau","Topspin","Score exact 50","Product ID Google Play","mDNS"]) must(master.includes(`title: \"${needle}\"`),`Critical V8.9 topic: ${needle}`);
for (const needle of ["Générer un AAB Android propre","Mettre à jour les testeurs Google Play","Diagnostiquer des profils locaux lents","Mettre l’application à jour sans risquer ses données","Diagnostiquer Cast sur un réseau local compliqué"]) must(proc.includes(`title: \"${needle}\"`),`Critical V8.9 tutorial: ${needle}`);
must(academy.includes("...AWENA_V89_PROCEDURES"),"V8.9 procedures wired into Procedural Academy");
must(core.includes("answerAwenaMasterKnowledgeV89") && core.includes("awenaMasterKnowledgeV89Count"),"V8.9 Master Knowledge wired into AwenaCore");
must(overlay.includes("LOCAL V8.9") && overlay.includes("MASTER KNOWLEDGE"),"Overlay advertises V8.9 Master Knowledge");
must(pkg.scripts["test:awena:v89"] === "node tools/test-awena-v89-master-knowledge.mjs","package V8.9 test script present");
console.log(`\n✅ AWENA V8.9 MASTER KNOWLEDGE: OK`);
console.log(`   ${entries.length} new knowledge topics`);
console.log(`   ${aliases} aliases / phrasings`);
console.log(`   ${procedures.length} new procedural tutorials`);
console.log(`   ${steps} guided steps / ${trouble} troubleshooting branches`);
